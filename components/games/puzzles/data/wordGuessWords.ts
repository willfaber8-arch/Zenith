const answersFor = (len: number): readonly string[] =>
  len === 4 ? ANSWERS_4 : len === 6 ? ANSWERS_6 : ANSWERS_5

const extraFor = (len: number): readonly string[] =>
  len === 4 ? EXTRA_4 : len === 6 ? EXTRA_6 : EXTRA_5

/** Per-length validity sets, built once. */
const VALID_SETS: Record<number, Set<string>> = {
  4: new Set([...ANSWERS_4, ...EXTRA_4].filter((w) => w.length === 4)),
  5: new Set([...ANSWERS_5, ...EXTRA_5].filter((w) => w.length === 5)),
  6: new Set([...ANSWERS_6, ...EXTRA_6].filter((w) => w.length === 6)),
}

/** True if `word` is an accepted guess for the given length (answer OR extra list). */
export function isValidGuess(word: string, len: number): boolean {
  const w = word.toLowerCase()
  if (w.length !== len) return false
  const set = VALID_SETS[len]
  return set ? set.has(w) : false
}

/** Pick a random answer of the given length. */
export function randomAnswer(len: number): string {
  const list = answersFor(len)
  return list[Math.floor(Math.random() * list.length)]
}

